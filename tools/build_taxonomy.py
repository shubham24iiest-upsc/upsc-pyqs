"""Write data/notebook-taxonomy.js: the subjects and topics the revision notebook offers.
It reuses the site's own tags: Prelims GS I subjects/topics (practice.html), CSAT sections (prelims-csat.js)
and the Mains GS paper topics (data/gs1.js ... gs4.js).
Run:  python3 tools/build_taxonomy.py
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent

def js_obj(text, var):
    t = text[text.index(f"window.{var}=") + len(f"window.{var}="):].strip()
    return json.loads(t[: t.index("\n")].rstrip(";") if "\n" in t else t.rstrip(";"))

html = (ROOT / "practice.html").read_text(encoding="utf-8")
pre = json.loads(re.search(r"window\.PRE\s*=\s*(\{.*?\});\s*\n", html, re.S).group(1))
csat = js_obj((ROOT / "prelims-csat.js").read_text(encoding="utf-8"), "CSAT_SEARCH")

groups = [{"name": "Prelims GS", "subjects": [{"name": s, "topics": t} for s, t in pre["topics"].items()]},
          {"name": "CSAT", "subjects": [{"name": s, "topics": t} for s, t in csat["topics"].items()]}]
mains = []
for k in ("gs1", "gs2", "gs3", "gs4"):
    src = (ROOT / "data" / f"{k}.js").read_text(encoding="utf-8")
    roman = re.search(r'roman:\s*"([^"]+)"', src).group(1)
    block = re.search(r"topics:\s*\[(.*?)\]", src, re.S).group(1)
    mains.append({"name": f"Mains GS {roman}", "topics": re.findall(r'"([^"]+)"', block)})
groups.append({"name": "Mains", "subjects": mains})

out = ("// Revision notebook subjects and topics, generated by tools/build_taxonomy.py from the site's question tags.\n"
       "window.PK_TAXONOMY=" + json.dumps(groups, ensure_ascii=False, separators=(",", ":")) + ";\n")
(ROOT / "data" / "notebook-taxonomy.js").write_text(out, encoding="utf-8")
print("wrote data/notebook-taxonomy.js:", sum(len(g["subjects"]) for g in groups), "subjects")
