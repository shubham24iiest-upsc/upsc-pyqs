#!/usr/bin/env python3
"""Build data/prelims-gs1-hi.js from the proofread Hindi text files in data/hindi/.

Each data/hindi/prelims-gs1-<year>.txt holds the Hindi questions exactly as printed
in the official bilingual UPSC paper (papers/PRE-GS1-<year>.pdf), in this layout:

    ### 12                      question number, same as the English paper
    question text, one line per printed line or list item
    (a) option
    (b) option
    (c) option
    (d) option

A line that is just one of the macros below stands for the four options UPSC
repeats word for word across questions. Tables use "| cell | cell" rows, like
the English data.

    python3 tools/build_hindi.py      # run from the repo root, then seo/build_pages.py
"""
import glob
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

MACROS = {
    "@D12": ["केवल I", "केवल II", "I और II दोनों", "न तो I और न ही II"],
    "@C123": ["केवल I और II", "केवल II और III", "केवल I और III", "I, II और III"],
    "@N4": ["केवल एक", "केवल दो", "केवल तीन", "सभी चार"],
    "@N3K": ["केवल एक", "केवल दो", "सभी तीन", "कोई नहीं"],
    "@N3B": ["केवल एक", "केवल दो", "सभी तीन", "कोई भी नहीं"],
    "@N3R": ["केवल एक", "केवल दो", "सभी तीन", "किसी में भी नहीं"],
    "@KS2": [
        "कथन I और कथन II दोनों सही हैं तथा कथन II, कथन I की व्याख्या करता है",
        "कथन I और कथन II दोनों सही हैं किन्तु कथन II, कथन I की व्याख्या नहीं करता है",
        "कथन I सही है किन्तु कथन II सही नहीं है",
        "कथन I सही नहीं है किन्तु कथन II सही है",
    ],
    "@KS3": [
        "कथन II और कथन III दोनों सही हैं तथा वे दोनों कथन I की व्याख्या करते हैं",
        "कथन II और कथन III दोनों सही हैं किन्तु उनमें से केवल एक, कथन I की व्याख्या करता है",
        "कथन II और कथन III में से केवल एक सही है तथा वह कथन I की व्याख्या करता है",
        "न तो कथन II और न ही कथन III सही है",
    ],
}
ROMAN = re.compile(r"^\|? ?(I|II|III|IV|V|VI|VII|VIII)\. ", re.M)


def parse(path):
    qs, cur = {}, None
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        line = line.rstrip("\n").strip()
        if not line:
            continue
        if line.startswith("### "):
            cur = {"q": [], "o": []}
            qs[line[4:].strip()] = cur
        elif line in MACROS:
            cur["o"].extend(MACROS[line])
        elif re.match(r"^\([a-d]\) ", line):
            cur["o"].append(line[4:])
        elif line.startswith("@"):
            sys.exit(f"{path}:{n}: unknown macro {line}")
        else:
            cur["q"].append(line)
    return {k: ["\n".join(v["q"]), v["o"]] for k, v in qs.items()}


def english():
    js = ("const fs=require('fs'),vm=require('vm');const c={window:{}};vm.createContext(c);"
          "vm.runInContext(fs.readFileSync('prelims-gs1.js','utf8'),c);"
          "process.stdout.write(JSON.stringify(c.window.PRE_SEARCH.qs))")
    rows = json.loads(subprocess.run(["node", "-e", js], cwd=ROOT, check=True,
                                     capture_output=True, text=True).stdout)
    return {(r[0], r[1]): r for r in rows}


def main():
    en = english()
    out, problems = {}, []
    for path in sorted(glob.glob(os.path.join(ROOT, "data/hindi/prelims-gs1-*.txt"))):
        year = int(re.search(r"(\d{4})\.txt$", path).group(1))
        qs = parse(path)
        for k, (q, opts) in qs.items():
            row = en.get((year, int(k)))
            if not row:
                problems.append(f"{year} Q{k}: no English question with this number")
                continue
            if len(opts) != 4:
                problems.append(f"{year} Q{k}: {len(opts)} options")
            if len(ROMAN.findall(q)) != len(ROMAN.findall(row[4])):
                problems.append(f"{year} Q{k}: {len(ROMAN.findall(q))} numbered items, English has {len(ROMAN.findall(row[4]))}")
        missing = sorted(n for (y, n) in en if y == year and str(n) not in qs)
        if missing:
            problems.append(f"{year}: missing questions {missing}")
        out[str(year)] = dict(sorted(qs.items(), key=lambda kv: int(kv[0])))
    if problems:
        sys.exit("\n".join(problems))
    with open(os.path.join(ROOT, "data/prelims-gs1-hi.js"), "w", encoding="utf-8") as f:
        f.write("// Prelims GS I questions in Hindi, as printed in UPSC's official bilingual papers.\n"
                "// Generated by tools/build_hindi.py from data/hindi/*.txt. Edit those files, not this one.\n"
                "// PRE_HI[year][qno] = [question, [a, b, c, d]]; subject, topic and answer come from prelims-gs1.js.\n"
                f"window.PRE_HI={json.dumps(out, ensure_ascii=False, separators=(',', ':'))};\n")
    print("wrote data/prelims-gs1-hi.js:", ", ".join(f"{y} ({len(v)} questions)" for y, v in out.items()))


if __name__ == "__main__":
    main()
